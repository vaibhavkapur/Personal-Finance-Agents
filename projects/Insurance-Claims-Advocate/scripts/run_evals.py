"""Run the labeled evaluation cases against the agent and the rules-only workflow; write docs/eval-report.json + .md."""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app.evals import run_all  # noqa: E402


def main() -> int:
    report = run_all()
    out_json = ROOT / "docs" / "eval-report.json"
    out_md = ROOT / "docs" / "eval-report.md"
    out_json.write_text(json.dumps(report, indent=2) + "\n")
    s = report["summary"]
    lines = [
        "# Evaluation report",
        "",
        f"Fixture version: `{s['fixture_version']}` · cases: {s['cases']} · generated by `scripts/run_evals.py`.",
        "",
        "Measured on the synthetic fixtures against the mock insurer. These are prototype regression results, not customer or market outcomes.",
        "",
        "| mode | passed | held-out passed | unnecessary questions | missed questions | unsupported statements | tool calls / case | seconds |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for mode, m in s["modes"].items():
        lines.append(f"| {mode} | {m['passed']}/{m['total']} | {m['held_out_passed']}/{m['held_out_total']} | {m['unnecessary_questions']} | {m['missed_questions']} | {m['unsupported_statements']} | {m['tool_calls_per_case']} | {m['seconds_total']} |")
    lines += ["", "## By category", ""]
    for mode, m in s["modes"].items():
        lines.append(f"### {mode}")
        lines.append("")
        for cat, c in m["by_category"].items():
            lines.append(f"- {cat}: {c['passed']}/{c['total']}")
        lines.append("")
    failures = [r for r in report["results"] if not r["passed"]]
    lines += ["## Failures", ""]
    if not failures:
        lines.append("None.")
    for r in failures:
        lines.append(f"- `{r['id']}` ({r['mode']}): " + "; ".join(r["mismatches"]) + (f"; unsupported statements: {r['unsupported_statements']}" if r["unsupported_statements"] else ""))
    lines += ["", "## Per-case results", "", "| case | category | held-out | agent | rules | agent tool calls | notes |", "|---|---|---|---|---|---|---|"]
    by_id = {}
    for r in report["results"]:
        by_id.setdefault(r["id"], {})[r["mode"]] = r
    cases = {c["id"]: c for c in __import__("app.evals", fromlist=["load_cases"]).load_cases()}
    for cid, modes in by_id.items():
        a = modes.get("agent")
        b = modes.get("rules")
        lines.append(f"| {cid} | {a['category'] if a else b['category']} | {'yes' if (a or b)['held_out'] else ''} | {'pass' if a and a['passed'] else 'FAIL'} | {'pass' if b and b['passed'] else 'FAIL'} | {a['tool_calls'] if a else ''} | {cases.get(cid, {}).get('notes', '')} |")
    out_md.write_text("\n".join(lines) + "\n")
    print(json.dumps(s, indent=2))
    for r in failures:
        print("FAIL", r["id"], r["mode"], r["mismatches"])
    return 0 if not failures else 1


if __name__ == "__main__":
    raise SystemExit(main())
