"""Run the labeled evaluation set for the agent and the rules-only baseline.

    python scripts/eval.py            # prints the summary
    python scripts/eval.py --write    # also writes docs/eval-report.md
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from backend.app.evaluation import evaluate, load_specs  # noqa: E402


def render(report) -> str:
    s = report["summary"]
    lines = ["# Evaluation report (generated by `python scripts/eval.py --write`)", "",
             f"Fixture version: `{s['fixture_version']}` / eval cases: `{json.loads((ROOT / 'fixtures' / 'eval_cases.json').read_text())['fixture_version']}` / cases: {s['cases']}", "",
             "Both modes run the same scripted timelines against the simulators and are compared on **state and evidence**, not wording. "
             "The agent mode uses the deterministic `RulesPlanner` behind the tool-calling interface (no LLM credentials in this repository), so its numbers "
             "describe the tool loop, guardrail and budget, not a language model. Swap `OpenAICompatibleModel` in to measure a real model with the same harness.", ""]
    lines.append("| mode | split | cases | passed | unnecessary questions | unsupported claims emitted | claims blocked by guardrail | tool calls | escalations |")
    lines.append("|---|---|---|---|---|---|---|---|---|")
    for mode, m in s["modes"].items():
        for split, b in m["by_split"].items():
            lines.append(f"| {mode} | {split} | {b['cases']} | {b['passed']} | {b['unnecessary_questions']} | {b['unsupported_claims_emitted']} | {b['claims_prevented_by_guardrail']} | {b['tool_calls']} | {b['escalations']} |")
    lines += ["", "## Per-case results (agent mode)", "", "| id | split | family | status | final | outstanding | provisional | store | reversed | question | proposed action | passed |", "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in report["results"]["agent"]:
        o = r["observed"]
        lines.append(f"| {r['id']} | {r['split']} | {r['family']} | {o['status']} | {o['final_minor']} | {o['outstanding_minor']} | {o['provisional_minor']} | {o['store_credit_minor']} | {o['reversed_minor']} | {o['question_kind'] or ''} | {o['proposed_action'] or ''} | {'yes' if r['passed'] else 'NO: ' + json.dumps(r['diffs'])} |")
    lines += ["", "Amounts are integer minor units (USD cents). `passed` means every labeled field matched exactly."]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    report = evaluate(load_specs())
    print(json.dumps(report["summary"], indent=2))
    if args.write:
        out = ROOT / "docs" / "eval-report.md"
        out.write_text(render(report))
        print(f"wrote {out}")


if __name__ == "__main__":
    main()
